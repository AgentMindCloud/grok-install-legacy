const CANONICAL_SAFETY_MD = `# SAFETY.md — grok-install hard limits

This document defines the **non-negotiable safety floor** every agent built with grok-install must satisfy. The \`safety-scanner.js\` validates every YAML against these rules. Agents failing any check cannot be minted.

## Hard rules (machine-enforced)

### Behavior
1. **Reply-only on mention** — agents never proactively message anyone. No keyword scanning of public posts.
2. **No DMs** — the \`send_dm\` tool requires explicit owner approval and is disabled by default.
3. **No mass actions** — auto-follow, auto-like, auto-quote are blocked unless explicitly enabled and rate-limited.
4. **Honors opt-out immediately** — agent receives \`OPTOUT\` mention from any user → never replies to that user again.
5. **No deepfakes** — mascot generation is locked to 8 stylized illustration prompts. No real-person likenesses.

### Identity
6. **Clear AI labeling** — agent's bio must contain one of: \`AI\`, \`Bot\`, \`Powered by Grok\`.
7. **Pretend-human disallowed** — when asked "are you a bot?" the agent must answer truthfully.

### Limits
8. **Rate-limited** — \`qps\`, \`daily_replies\`, and \`daily_usd_cap\` are declared in YAML and enforced by the runtime.
9. **No bypass** — agents cannot dynamically alter their own limits at runtime.

### Security
10. **No hardcoded keys** — scanner rejects any YAML with literal API keys or secrets.
11. **Minimum scopes** — agents request only the tools they actively use.

## Owner consent for updates

Agents do not auto-update. The owner approves every change explicitly.

## Reporting issues

If you find an agent violating these rules: open an issue at https://github.com/AgentMindCloud/grok-install/issues
`;

function escapeYaml(s) {
  return String(s).replace(/"/g, '\\"');
}

export function buildAgentYaml({
  agentName,
  slug,
  genesisId,
  description,
  agentHandle,
  ownerHandle,
  ownerGithub,
  profile,
  mascotStyle,
  optInWall = true,
  templateName = null,
  bilingual = false,
  features = null,
  limits = null,
  blockedUsers = [],
}) {
  const voice = (profile?.voice_traits ?? ['direct', 'helpful']).map(v => `"${escapeYaml(v)}"`).join(', ');
  const domains = (profile?.domains ?? []).map(v => `"${escapeYaml(v)}"`).join(', ');
  const vibe = (profile?.vibe ?? ['friendly']).map(v => `"${escapeYaml(v)}"`).join(', ');
  const sigs = (profile?.signature_phrases ?? []).map(v => `"${escapeYaml(v)}"`).join(', ');
  const dailyReplies = limits?.daily_replies ?? 200;
  const qps = limits?.qps ?? 0.5;
  const dailyUsd = limits?.daily_usd_cap ?? 3;
  const cooldown = limits?.cooldown_seconds ?? 30;
  const maxThreadDepth = limits?.max_thread_depth ?? 5;
  const f = features || {};
  const blocklist = (blockedUsers || [])
    .map(h => `"${escapeYaml(h.replace(/^@/, ''))}"`)
    .join(', ');

  return `# grok-install.yaml — generated by grok-install
# Genesis ${genesisId}
# Agent: ${agentName}

name: "${escapeYaml(agentName)}"
slug: ${slug}
genesis_id: "${genesisId}"
description: "${escapeYaml(description)}"
version: "1.0.0"
manifest_url: "https://agentmindcloud.github.io/grok-install/manifest.json"
features_version: 1
${templateName ? `source_template: "${escapeYaml(templateName)}"\n` : ''}
brain:
  provider: xai
  model: grok-4
  temperature: 0.7
  system_prompt_overlay: |
    You are an X-native AI agent. Your personality is defined below.
    Reply only when @mentioned. Never DM. Never make claims you can't verify.
    Always identify yourself as an AI when asked.

personality:
  voice: [${voice}]
  domains: [${domains}]
  vibe: [${vibe}]
  signature_phrases: [${sigs}]
  mascot_style: "${escapeYaml(mascotStyle || 'specimen_plate')}"
  bilingual: ${bilingual ? 'true' : 'false'}

limits:
  daily_replies: ${dailyReplies}
  qps: ${qps}
  daily_usd_cap: ${dailyUsd}
  max_thread_depth: ${maxThreadDepth}
  cooldown_seconds: ${cooldown}

tools:
  - read_mentions
  - reply_to_mentions
  - post_text

features:
  image_posting:
    enabled: ${f?.image_posting?.enabled ? 'true' : 'false'}
    daily_limit: ${f?.image_posting?.daily_limit ?? 10}
    credit_impact: high
    requires_owner_approval: false
  analytics:
    enabled: ${f?.analytics?.enabled === false ? 'false' : 'true'}
    retention_days: ${f?.analytics?.retention_days ?? 30}
    credit_impact: low
  memory:
    enabled: ${f?.memory?.enabled ? 'true' : 'false'}
    max_kb: ${f?.memory?.max_kb ?? 50}
    credit_impact: medium
  bilingual_replies:
    enabled: ${f?.bilingual_replies?.enabled ? 'true' : 'false'}
    credit_impact: low
  advanced_tools:
    enabled: ${f?.advanced_tools?.enabled ? 'true' : 'false'}
    credit_impact: very_high
    requires_owner_approval: true
  custom_commands:
    enabled: ${f?.custom_commands?.enabled ? 'true' : 'false'}
    extra_commands: ${f?.custom_commands?.extra_commands ?? 0}
    credit_impact: low

safety:
  pre_install_scan: true
  minimum_keys_only: true
  audit_log: true
  content_moderation: true
  mention_only: true
  clear_ai_labeling: true
  approval_required:
    - send_dm
    - follow_users
  rate_limit_strategy: strict
  optout_honored: true
  blocked_users: [${blocklist}]

commands:
  default:
    description: "Reply in agent's voice."
    accessible_to: anyone
  help:
    description: "List what this agent can do, who built it."
    accessible_to: anyone
  whatsnew:
    description: "Pull latest news from grok-install news feed."
    accessible_to: anyone
    feed_url: "https://agentmindcloud.github.io/grok-install/news.json"
  update:
    description: "Check for and apply template updates (owner-consent only)."
    accessible_to: owner_only

x_account:
  handle: "@${escapeYaml(agentHandle.replace(/^@/, ''))}"
  bio_required_words:
    - "AI"
    - "Bot"
    - "Powered by Grok"

owner:
  handle: "@${escapeYaml(ownerHandle.replace(/^@/, ''))}"
  github: "${escapeYaml(ownerGithub)}"
  minted_at: "${new Date().toISOString()}"

wall:
  opt_in: ${optInWall ? 'true' : 'false'}
  show_handle: true
  show_mascot: true

provenance:
  built_with: "grok-install"
  template_version: "1.5.0"
  source: "https://github.com/AgentMindCloud/grok-install"
  creator_credit: "@JanSol0s"
`;
}

